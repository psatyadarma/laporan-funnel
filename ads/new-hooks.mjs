// Asks the AI for fresh hook ideas per bet (one per awareness level), for the next round of tests.
//   AI_API_KEY=... node ads/new-hooks.mjs [--app URL]
// Writes ads/out/hook-ideas.md. Review them, then add the good ones to the bet config and ads/copy.mjs.
import { mkdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { CAMPAIGNS } from './copy.mjs';

const args = process.argv.slice(2);
const appArg = args.includes('--app') ? args[args.indexOf('--app') + 1] : undefined;
const APP = (appArg ?? process.env.APP_URL ?? 'https://laporan-funnel.psatyadarma2.workers.dev').replace(/\/$/, '');
const key = process.env.AI_API_KEY;
if (!key) { console.error('Set AI_API_KEY'); process.exit(2); }
const base = (process.env.AI_BASE_URL ?? 'https://openrouter.ai/api/v1').replace(/\/$/, '');
const model = process.env.AI_MODEL ?? 'anthropic/claude-sonnet-5.5';

let md = `# Hook ideas (${new Date().toISOString().slice(0, 10)})\n\nGenerated by ${model}. Review before using: check Meta policy, honesty, and that the landing page keeps the promise.\n`;
for (const slug of Object.keys(CAMPAIGNS)) {
  const bet = await (await fetch(`${APP}/api/bets/${slug}`)).json();
  const existing = bet.hooks.map((h) => `- ${h.headline}`).join('\n');
  const prompt = `Produk: ${bet.brand}. Halaman: ${bet.hooks[0].sub}\nHook yang sudah diuji:\n${existing}\n\n` +
    `Tulis 10 hook iklan baru dalam Bahasa Indonesia sehari-hari untuk Instagram/TikTok, masing-masing maksimal 12 kata, untuk 5 tingkat kesadaran pembeli (2 per tingkat): ` +
    `1) ajarkan satu hal, 2) kenapa cara lain gagal, 3) momen yang mereka kenal (POV), 4) sebut rasa sakitnya, 5) dorongan untuk mulai. ` +
    `Aturan: tanpa janji penghasilan, kekayaan, nasib, atau hasil pasti; tidak menyinggung agama; tidak menakut-nakuti berlebihan. ` +
    `Format: daftar bernomor, setiap baris "[tingkat] hook | alasan singkat".`;
  const res = await fetch(`${base}/chat/completions`, {
    method: 'POST',
    headers: { Authorization: `Bearer ${key}`, 'Content-Type': 'application/json' },
    body: JSON.stringify({ model, temperature: 0.9, max_tokens: 2000, messages: [{ role: 'user', content: prompt }] }),
  });
  const json = await res.json();
  md += `\n## ${bet.brand}\n\n${json.choices?.[0]?.message?.content ?? `Error: ${JSON.stringify(json).slice(0, 300)}`}\n`;
  console.log(`✓ ${slug}`);
}
mkdirSync(resolve(import.meta.dirname, 'out'), { recursive: true });
writeFileSync(resolve(import.meta.dirname, 'out/hook-ideas.md'), md);
console.log('Wrote ads/out/hook-ideas.md');
